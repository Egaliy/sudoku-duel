const read = () => { try { return localStorage.getItem("sd-lang"); } catch { return null; } };

// Основной язык — английский; русский и сербский выбираются в настройках (шестерёнка).
export const lang = ["en", "ru", "sr"].includes(read()) ? read() : "en";
export const T = { en, ru, sr }[lang];
document.documentElement.lang = lang === "sr" ? "sr-Latn" : lang;
document.title = T.title;

export function setLang(l) {
  if (l === lang) return;
  try { localStorage.setItem("sd-lang", l); } catch {}
  location.reload();
}

