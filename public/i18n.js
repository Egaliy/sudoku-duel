// Кнопка настроек (шестерёнка) и лист с выбором языка
export const langSwitchHTML = () => `<button class="gear-btn" data-settings aria-label="${T.settings}">${GEAR}</button>`;
export function bindLangSwitch(root) {
  root.querySelectorAll("[data-settings]").forEach((b) => (b.onclick = openSettings));
}
export function openSettings() {
  const wrap = document.createElement("div");
  wrap.className = "sheet-wrap";
  wrap.innerHTML = `<div class="card settings-sheet">
    <div class="chat-head"><span>${T.settings}</span><button class="close" style="color:var(--accent);font-weight:600">${T.done}</button></div>
    <div class="set-sec">${T.language}</div>
    <div class="set-list">${LANGS.map(([k, name]) => `<button class="set-row${k === lang ? " on" : ""}" data-l="${k}"><span>${name}</span><i>✓</i></button>`).join("")}</div>
  </div>`;
  const close = () => wrap.remove();
  wrap.onclick = (e) => { if (e.target === wrap) close(); };
  wrap.querySelector(".close").onclick = close;
  wrap.querySelectorAll("[data-l]").forEach((b) => (b.onclick = () => setLang(b.dataset.l)));
  document.body.append(wrap);
}
